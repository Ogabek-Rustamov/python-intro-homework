print(not True and False)  # False: not True becomes False; False and False is False.

print(True or False and False)  # True: and is evaluated first, so True or False is True.

print(not (5 > 3))  # False: 5 > 3 is True, and not True is False.

print(10 == 10 and 4 != 4)  # False: the first comparison is True, but the second is False.

print(not False or not True)  # True: not False is True, and True or False is True.
